#!/usr/bin/env bash
# Opens three sparq EARL report PRs, one each on w3c/rdf-tests, w3c/rdf-canon and w3c/json-ld-api.
# It uses your gh login. It forks each repository to your account if the fork doesn't exist yet,
# pushes a branch to the fork, and opens the PR. The reports are read from this branch's earl/ folder.
set -euo pipefail
me="$(gh api user --jq .login)"
src=https://raw.githubusercontent.com/sparq-org/sparq/wip/earl-reports-20261112/earl
work="$(mktemp -d)"

# open_pr <repo> <branch> <title> <body file> <report file>:<path in repo> ...
open_pr() {
  local repo="$1" branch="$2" title="$3" body="$4"; shift 4
  gh repo fork "w3c/$repo" --clone=false >/dev/null 2>&1 || true
  local base
  base="$(gh api "repos/w3c/$repo" --jq .default_branch)"
  git clone -q --depth 1 -b "$base" "https://github.com/w3c/$repo.git" "$work/$repo"
  cd "$work/$repo"
  git checkout -q -b "$branch"
  local pair file dest
  for pair in "$@"; do
    file="${pair%%:*}"; dest="${pair#*:}"
    curl -fsSL "$src/$file" -o "$dest"
    git add "$dest"
  done
  git commit -q -m "$title"
  git push -q --force-with-lease "https://github.com/$me/$repo.git" "$branch"
  gh pr create --repo "w3c/$repo" --base "$base" --head "$me:$branch" --title "$title" --body-file "$body"
  cd "$work"
}

cat > "$work/rdf12.md" <<'EOF'
This adds EARL reports for [sparq](https://github.com/sparq-org/sparq) against the RDF 1.2 Turtle, TriG, N-Triples and N-Quads test suites.

- Turtle: 109 of 109 pass (syntax and evaluation).
- TriG: 64 of 64 pass (syntax and evaluation).
- N-Triples: 75 of 75 pass (syntax and canonical form).
- N-Quads: 72 of 72 pass (syntax and canonical form).
- Built from sparq commit `7f372aa9da9db1509fb6cec6bac0c3cda82d9c95` and run against this repository at commit `7b5afb91857a9c282c03d2e45d3f76485797c901`. Generated by `crates/sparq-conformance/earl-report.sh`, which records each manifest entry's outcome from sparq's own suite runners.
EOF
open_pr rdf-tests sparq-rdf12-earl "Add sparq RDF 1.2 Turtle, TriG, N-Triples and N-Quads reports" "$work/rdf12.md" \
  sparq-rdf12-rdf-turtle-earl.ttl:rdf/rdf12/rdf-turtle/reports/sparq-earl.ttl \
  sparq-rdf12-rdf-trig-earl.ttl:rdf/rdf12/rdf-trig/reports/sparq-earl.ttl \
  sparq-rdf12-rdf-n-triples-earl.ttl:rdf/rdf12/rdf-n-triples/reports/sparq-earl.ttl \
  sparq-rdf12-rdf-n-quads-earl.ttl:rdf/rdf12/rdf-n-quads/reports/sparq-earl.ttl

cat > "$work/canon.md" <<'EOF'
This adds an EARL report for [sparq](https://github.com/sparq-org/sparq) against the RDFC-1.0 test suite.

- 86 of 86 tests pass, covering evaluation, identifier maps and negative evaluation, including the SHA-384 tests.
- Built from sparq commit `7f372aa9da9db1509fb6cec6bac0c3cda82d9c95` (the `sparq-canon` crate) and run against this repository at commit `15619df2fda7a4ca88308733789b6774517f9638`. Generated by `crates/sparq-conformance/earl-report.sh`.
EOF
open_pr rdf-canon sparq-earl "Add sparq RDFC-1.0 implementation report" "$work/canon.md" \
  sparq-rdf-canon-earl.ttl:reports/sparq-earl.ttl

cat > "$work/jsonld.md" <<'EOF'
This adds an EARL report for [sparq](https://github.com/sparq-org/sparq) as a JSON-LD 1.1 processor, covering the API test suites here and the framing tests from w3c/json-ld-framing.

- 1186 of 1298 reported tests pass: expand 368 of 368, compact 232 of 233, flatten 53 of 55, fromRdf 53 of 53, toRdf 407 of 448, frame 73 of 73.
- The 112 failures are reported as failed, not omitted: HTML script extraction (50, not implemented yet), remote documents (18, no document loader wired yet), and 44 toRdf, compact and flatten cases, including relative remote contexts, expected errors that sparq does not raise yet, and base-direction handling.
- JSON-LD 1.0-only entries (`specVersion` or `processingMode` `json-ld-1.0`) are omitted as not applicable to a 1.1 processor.
- Built from sparq commit `7f372aa9da9db1509fb6cec6bac0c3cda82d9c95` and run against w3c/json-ld-api at `55514738d854e56bb8bad4c53cda2f0e23be4a50` and w3c/json-ld-framing at `3bf782ba9a40dd1b143435abe386d38df64f2b47`. Generated by `crates/sparq-conformance/earl-report.sh`.
EOF
open_pr json-ld-api sparq-earl "Add sparq JSON-LD implementation report" "$work/jsonld.md" \
  sparq-json-ld-earl.ttl:reports/sparq-earl.ttl
