#!/usr/bin/env bash
# 1. Adds the RDF/XML 1.2 report to the open RDF 1.2 PR (w3c/rdf-tests#416) and refreshes its other reports.
# 2. Opens one new PR on w3c/rdf-tests with sparq's RDF 1.1 reports (Turtle, TriG, N-Triples, N-Quads, RDF/XML, Semantics).
# It uses your gh login and your existing fork of w3c/rdf-tests. Nothing is force-pushed.
set -euo pipefail
me="$(gh api user --jq .login)"
src=https://raw.githubusercontent.com/sparq-org/sparq/wip/earl-reports-20261112/earl
work="$(mktemp -d)"
fetch() { curl -fsSL "$src/$1" -o "$2"; git add "$2"; }

# --- 1. Update #416 -------------------------------------------------------------------------
git clone -q --depth 1 -b sparq-rdf12-earl "https://github.com/$me/rdf-tests.git" "$work/rdf12"
cd "$work/rdf12"
for s in turtle trig n-triples n-quads xml; do
  fetch "sparq-rdf12-rdf-$s-earl.ttl" "rdf/rdf12/rdf-$s/reports/sparq-earl.ttl"
done
git commit -q -m "Add sparq RDF/XML 1.2 report and refresh the RDF 1.2 reports"
git push -q "https://github.com/$me/rdf-tests.git" sparq-rdf12-earl
cat > "$work/rdf12.md" <<'EOF'
This adds EARL reports for [sparq](https://github.com/sparq-org/sparq) against the RDF 1.2 Turtle, TriG, N-Triples, N-Quads and RDF/XML test suites.

- Turtle: 109 of 109 pass (syntax and evaluation).
- TriG: 64 of 64 pass (syntax and evaluation).
- N-Triples: 75 of 75 pass (syntax and canonical form).
- N-Quads: 72 of 72 pass (syntax and canonical form).
- RDF/XML: 29 of 31 pass. Two evaluation cases fail and are reported as failed. RDF/XML parsing is an opt-in sparq feature (`rdfxml`), which was enabled for this run.
- Built from sparq commit `77072da807ad658244c8702d24ec774fae3ae35b` and run against this repository at commit `7b5afb91857a9c282c03d2e45d3f76485797c901`. Generated by `crates/sparq-conformance/earl-report.sh`, which records each manifest entry's outcome from sparq's own suite runners. Withdrawn or rejected upstream entries are omitted; unsupported entries are reported as failed.
EOF
gh pr edit 416 --repo w3c/rdf-tests \
  --title "Add sparq RDF 1.2 Turtle, TriG, N-Triples, N-Quads and RDF/XML reports" --body-file "$work/rdf12.md"

# --- 2. New RDF 1.1 PR ----------------------------------------------------------------------
cd "$work"
git clone -q --depth 1 https://github.com/w3c/rdf-tests.git rdf11
cd rdf11
git checkout -q -b sparq-rdf11-earl
for s in turtle trig n-triples n-quads xml mt; do
  fetch "sparq-rdf11-rdf-$s-earl.ttl" "rdf/rdf11/rdf-$s/reports/sparq-earl.ttl"
done
git commit -q -m "Add sparq RDF 1.1 implementation reports"
git push -q "https://github.com/$me/rdf-tests.git" sparq-rdf11-earl
cat > "$work/rdf11.md" <<'EOF'
This adds EARL reports for [sparq](https://github.com/sparq-org/sparq) against the RDF 1.1 test suites.

- Turtle: 313 of 313 pass.
- TriG: 357 of 357 pass.
- N-Triples: 70 of 70 pass.
- N-Quads: 87 of 87 pass.
- RDF/XML: 164 of 166 pass. Two evaluation cases fail and are reported as failed. RDF/XML parsing is an opt-in sparq feature (`rdfxml`), which was enabled for this run.
- RDF 1.1 Semantics: 48 of 48 pass.
- Built from sparq commit `77072da807ad658244c8702d24ec774fae3ae35b` and run against this repository at commit `7b5afb91857a9c282c03d2e45d3f76485797c901`. Generated by `crates/sparq-conformance/earl-report.sh`. Withdrawn or rejected upstream entries are omitted; unsupported entries are reported as failed.
EOF
gh pr create --repo w3c/rdf-tests --base main --head "$me:sparq-rdf11-earl" \
  --title "Add sparq RDF 1.1 implementation reports" --body-file "$work/rdf11.md"
