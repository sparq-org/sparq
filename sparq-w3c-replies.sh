#!/usr/bin/env bash
# Answers the open questions on sparq's W3C report PRs. Uses your gh login. Safe to run again:
# each step is skipped if it was already done.
#   1. Opens a SPARQL-RL issue on w3c/data-shapes with the three test/spec disagreements
#      Andy Seaborne asked about on #1449, and replies to him on #1449 with the details.
#   2. Posts a short ready-to-merge note on the approved PRs rdf-tests#415, #416 and json-ld-api#742.
set -euo pipefail
me="$(gh api user --jq .login)"
src=https://raw.githubusercontent.com/sparq-org/sparq/wip/earl-reports-20261112/replies-20261114
work="$(mktemp -d)"
footer=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
title='SRL: wellformed-group-04, wellformed-group-09 and eval-group-09 expect rules that inUse (#690) now rejects'

# commented <repo> <number> <marker>: true if you already left a comment containing <marker>
commented() {
  [ -n "$(gh api "repos/w3c/$1/issues/$2/comments" --paginate \
    --jq ".[] | select(.user.login == \"$me\" and (.body | contains(\"$3\"))) | .id")" ]
}

# --- 1. data-shapes ---------------------------------------------------------------------------
issue="$(gh issue list --repo w3c/data-shapes --author "$me" --state all --search "wellformed-group-09 eval-group-09 in:title" --json url --jq '.[0].url // empty')"
if [ -z "$issue" ]; then
  curl -fsSL "$src/issue-srl.md" -o "$work/issue.md"
  issue="$(gh issue create --repo w3c/data-shapes --title "$title" --label SPARQL-RL --body-file "$work/issue.md")"
fi
echo "SPARQL-RL issue: $issue"
if ! commented data-shapes 1449 "dated version"; then
  gh pr comment 1449 --repo w3c/data-shapes --body "Thanks Andy, and sorry for the vague pointer.

- **Which dated version:** the SPARQL-RL editor's draft in this repository at 04ecbb4, which is your GH-690 change (\`CHANGES.md\` entry 2026-11-10), with the tests at the same commit.
- **Research record:** [research/sparql-rl.md](https://github.com/sparq-org/sparq/blob/2a1c2d909b1c819012e5d1a047767665bd2945be/research/sparql-rl.md#pinned-manifest-census) and the [SPARQL-RL section](https://github.com/sparq-org/sparq/blob/2a1c2d909b1c819012e5d1a047767665bd2945be/research/shacl12-conformance-gap.md#inference-rules-and-sparql-rl) of the conformance notes.
- **Issue:** $issue, labelled SPARQL-RL, with a short description and the inScope/inUse working for each test. In short, \`wellformed-group-04\` and \`eval-group-09\` set a non-key variable from before the GROUP again inside the group pattern, and \`wellformed-group-09\` reuses \`?y\` from the first GROUP in the second. Both are excluded by the 2026-11-10 text, so these look like tests written before GH-690 and may belong with #1444.$footer"
fi

# --- 2. ready notes --------------------------------------------------------------------------
ci_note='The red checks are not from this PR: the report job fails at Ruby setup on the new ubuntu-26.04 runners (fixed by #417), and "Add PR to project" needs its `ADD_TO_PROJECT_PAT` secret refreshed.'
if ! commented rdf-tests 415 "Ready to merge from our side"; then
  gh pr comment 415 --repo w3c/rdf-tests --body "Thanks for the reviews. Ready to merge from our side whenever convenient. $ci_note$footer"
fi
if ! commented rdf-tests 416 "Ready to merge from our side"; then
  gh pr comment 416 --repo w3c/rdf-tests --body "Thanks for the review. Ready to merge from our side whenever convenient. To keep this PR as reviewed, the RDF/XML 1.2 report went into its own PR (#418). $ci_note$footer"
fi
if ! commented json-ld-api 742 "Ready to merge from our side"; then
  gh pr comment 742 --repo w3c/json-ld-api --body "Thanks for the review. One change since then: on 13 Nov I refreshed the report from a newer sparq build that adds HTML and remote-document support (now 1297 of 1298 pass; the description lists the details). Ready to merge from our side whenever convenient. #743 fixes the unrelated Ruby setup failure in the report job.$footer"
fi
echo "All done."
