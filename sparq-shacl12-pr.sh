#!/usr/bin/env bash
# Opens the sparq SHACL 1.2 report PR (and refreshes the SHACL 1.0 report) on w3c/data-shapes.
# Uses your gh login; pushes to your fork jeswr/data-shapes.
set -euo pipefail
d="$(mktemp -d)"; cd "$d"
git clone -q --depth 1 -b gh-pages https://github.com/w3c/data-shapes.git ds
cd ds
git checkout -q -b sparq-shacl12-earl
src=https://raw.githubusercontent.com/sparq-org/sparq/wip/earl-reports-20261112/earl
curl -fsSL "$src/sparq-shacl12-earl.ttl" -o shacl12-test-suite/reports/sparq-shacl12-earl.ttl
curl -fsSL "$src/sparq-shacl-earl.ttl" -o data-shapes-test-suite/reports/sparq-shacl-earl.ttl
git add shacl12-test-suite/reports/sparq-shacl12-earl.ttl data-shapes-test-suite/reports/sparq-shacl-earl.ttl
git commit -q -m "Add sparq SHACL 1.2 implementation report and refresh its SHACL 1.0 report"
git push -q --force-with-lease https://github.com/jeswr/data-shapes.git sparq-shacl12-earl
cat > "$d/body.md" <<'EOF'
This adds an EARL report for [sparq](https://github.com/sparq-org/sparq) against the SHACL 1.2 test suite in `shacl12-test-suite`, and refreshes sparq's SHACL 1.0 report.

- SHACL 1.2: 391 of 544 reported tests pass. Core passes 162 of 162, SHACL-SPARQL 98 of 98, and `node-expr/constraints` 8 of 8. All 153 failures are node-expression evaluation: `node-expr/shnex` 123 of 142, `node-expr/shnex-sparql` 0 of 112, `node-expr/custom` 0 of 22. Work on those is under way.
- `tests/inference-rules` and `tests/sparql-rl` are not reported yet, since sparq does not implement SHACL 1.2 inference rules yet.
- SHACL 1.0: now 120 of 120 (`sparql/pre-binding/shapesGraph-001` is fixed).
- Built from sparq commit `548d9448bb5cd17c71e43a013475de162428233a` with the `sparq-shacl` crate's `shacl-af` feature on, run against this repository at commit `ed480b837b9c8c06fcf92575bbdc4e9f840cdafd`. Generated by `crates/sparq-shacl/earl-report.sh`, which records each manifest entry's outcome from sparq's own suite runners.

Updated reports will follow as the remaining gaps close.
EOF
gh pr create --repo w3c/data-shapes --base gh-pages --head jeswr:sparq-shacl12-earl \
  --title "Add sparq SHACL 1.2 implementation report" --body-file "$d/body.md"
