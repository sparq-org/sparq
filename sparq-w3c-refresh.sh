#!/usr/bin/env bash
# Refreshes two sparq W3C reports from sparq main a09f266. Uses your gh login and forks.
# Nothing is force-pushed, and finished steps are skipped, so it is safe to run again.
#   1. Opens a PR on w3c/data-shapes replacing the SHACL 1.2 report (#1447 is already merged).
#   2. Updates the open JSON-LD PR w3c/json-ld-api#742 with the new report and description.
set -euo pipefail
me="$(gh api user --jq .login)"
work="$(mktemp -d)"
src=https://raw.githubusercontent.com/sparq-org/sparq/wip/earl-reports-20261112/earl/main-a09f266
footer=$'\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'

# --- 1. data-shapes: SHACL 1.2 refresh ------------------------------------------------------
branch=sparq-shacl12-refresh
if [ -n "$(gh pr list --repo w3c/data-shapes --head "$branch" --author "$me" --state all --json number --jq '.[].number')" ]; then
  echo "w3c/data-shapes: PR from $branch already exists, skipping"
else
  gh repo fork w3c/data-shapes --clone=false >/dev/null 2>&1 || true
  git clone -q --depth 1 -b gh-pages https://github.com/w3c/data-shapes.git "$work/data-shapes"
  cd "$work/data-shapes"
  git checkout -q -b "$branch"
  curl -fsSL "$src/sparq-shacl12-earl.ttl" -o shacl12-test-suite/reports/sparq-shacl12-earl.ttl
  git add -A && git commit -q -m "Refresh the sparq SHACL 1.2 implementation report"
  git push -q "https://github.com/$me/data-shapes.git" "$branch"
  gh pr create --repo w3c/data-shapes --base gh-pages --head "$me:$branch" \
    --title "Refresh the sparq SHACL 1.2 implementation report" --body "This replaces the sparq SHACL 1.2 report added in #1447 with a run from a newer sparq build that covers more of the suite.

- 926 of 933 reported tests pass. Core, SHACL-SPARQL (including the scope-interaction tests), custom functions, inference rules and SPARQL-RL syntax and stratification all pass in full.
- The 7 failures are reported as failed. Four are node-expression SPARQL-function cases (ceil, floor, round, seconds) where sparq returns the right value and datatype but a different lexical form (\`4\` for \`4.0\`, \`0\` for \`00\`). Three are SPARQL-RL cases (wellformed test_12 and test_17, and eval-group-09) where sparq follows its reading of the spec text; the reasoning is in sparq's research record.
- Built from sparq commit \`a09f266d94d80bde4f7a53e3a047d106d65c375f\` with the sparq-shacl \`shacl-af\` and \`sparql-rl\` features on, and run against this repository at \`04ecbb4a5b930f4fa9df6c399ac5c98ccec672c9\` (no test changes since). Generated by \`crates/sparq-shacl/earl-report.sh\`. Unsupported entries and fixture/spec disagreements are reported as failures.$footer"
  cd "$work"
fi

# --- 2. json-ld-api#742 refresh -------------------------------------------------------------
git clone -q --depth 1 -b sparq-earl "https://github.com/$me/json-ld-api.git" "$work/json-ld-api"
cd "$work/json-ld-api"
curl -fsSL "$src/sparq-json-ld-earl.ttl" -o reports/sparq-earl.ttl
if [ -z "$(git status --porcelain)" ]; then
  echo "w3c/json-ld-api#742: report already current"
else
  git add -A && git commit -q -m "Refresh the sparq JSON-LD report (HTML and remote documents)"
  git push -q "https://github.com/$me/json-ld-api.git" sparq-earl
fi
gh pr edit 742 --repo w3c/json-ld-api --body "This adds an EARL report for [sparq](https://github.com/sparq-org/sparq) as a JSON-LD 1.1 processor, covering the API test suites here and the framing tests from w3c/json-ld-framing.

- 1297 of 1298 reported tests pass: expand 368 of 368, compact 233 of 233, flatten 55 of 55, fromRdf 53 of 53, toRdf 448 of 448, html 49 of 50, remote-doc 18 of 18, frame 73 of 73.
- The one failure (html #tr006) is reported as failed.
- JSON-LD 1.0-only entries (\`specVersion\` or \`processingMode\` \`json-ld-1.0\`) are omitted as not applicable to a 1.1 processor.
- The report measures JSON-LD API operations in the \`sparq-jsonld\` crate. sparq's RDF store ingests JSON-LD through a different parser, which this report does not measure.
- Built from sparq commit \`a09f266d94d80bde4f7a53e3a047d106d65c375f\` and run against w3c/json-ld-api at \`55514738d854e56bb8bad4c53cda2f0e23be4a50\` and w3c/json-ld-framing at \`3bf782ba9a40dd1b143435abe386d38df64f2b47\`. Generated by \`crates/sparq-conformance/earl-report.sh\`.
- Updated since the first review: the earlier run predated sparq's HTML and remote-document support.$footer"
echo "All done."
